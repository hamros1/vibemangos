#!/usr/bin/env python3
"""Writes docs/COMMANDS.md from the command table and the handlers written.

    python3 tools/commands_doc.py

Reads source/dmangos/world/commandtable.d (the GM command tables) and the
`handle...(string args)` methods of the world modules, so the list of
commands, their permission letters, help texts and whether they work here
always match the code.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD = os.path.join(ROOT, "source", "dmangos", "world")

ROW = re.compile(r'ChatCommand\(("(?:[^"\\]|\\.)*"), \'(.)\', (null|"\w+"), ("(?:[^"\\]|\\.)*"), (\w+), '
                 r'(null|"[^"]*"), (null|"[^"]*"), (\d)\)')

LETTERS = {
    "0": "everyone with permissions",
    "a": "all but `z`",
    "z": "administrators",
}


def tables():
    text = open(os.path.join(WORLD, "commandtable.d")).read()
    found = {}
    for match in re.finditer(r"immutable ChatCommand\[\] (\w+) = \[(.*?)\n\];", text, re.S):
        rows = []
        for row in ROW.finditer(match.group(2)):
            name, group, handler, help_, child, field, _, _ = row.groups()
            rows.append({
                "name": name.strip('"'),
                "group": group,
                "handler": None if handler == "null" else handler.strip('"'),
                "help": help_[1:-1].replace('\\"', '"').replace("\\n", " "),
                "child": None if child == "null" else child,
                "field": field != "null",
            })
        found[match.group(1)] = rows
    return found


def implemented():
    names = set()
    # Most handlers live in gm*.d; a few with the system they command (honor.d's `.honor`).
    for path in glob.glob(os.path.join(WORLD, "gm*.d")) + [os.path.join(WORLD, n) for n in ("commands.d", "honor.d")]:
        for name in re.findall(r"bool (handle[A-Z]\w*)\(", open(path).read()):
            names.add(name[0].upper() + name[1:])
    return names


def main():
    all_tables = tables()
    done = implemented()
    rows_done, rows_todo = [], []
    for row in all_tables["commandTable"]:
        children = all_tables[row["child"]] if row["child"] else [None]
        for child in children:
            entry = child or row
            name = "." + row["name"] + ("" if child is None else " " + child["name"])
            letter = entry["group"]
            works = entry["field"] or (entry["handler"] in done)
            line = "| `%s` | `%s` | %s |" % (name, letter, entry["help"].replace("|", "\\|") or "")
            (rows_done if works else rows_todo).append(line)

    with open(os.path.join(ROOT, "docs", "COMMANDS.md"), "w") as out:
        out.write("""# GM commands

The GM system is ArcEmu 2.4.3's (`arcemu-world/Chat.cpp`, `Level0.cpp` .. `Level3.cpp`,
`debugcmds.cpp`, `RecallCommands.cpp`): its command tables row for row, its permission letters, its
lookup, and its replies, word for word. This file is generated by `tools/commands_doc.py`.

* **Typing:** a message starting with `.` or `!` is a command for an account with any permission
  (`allow_player_commands` lets everyone use the `0` ones); otherwise it is said aloud. Commands are
  read in say, yell, party, raid, guild, officer and channel chat, as in ArcEmu.
* **Lookup:** each word is matched against the rows in the order below, and the first row the word
  starts, and whose letter the account has, is taken: `.k` is `.kill`, `.gm o` is `.gm off`. A group
  alone (`.modify`) lists its commands. A command used wrongly shows its help text.
* **Permissions:** ArcEmu's letters. `a` grants every letter but `z`; `z` is the administrators';
  `0` commands need only some permission. CMaNGOS's `account.gmlevel` becomes letters through the
  `gm_permissions` setting: by default 1 (moderator) has `bcghiltuv`, 2 (game master) `a`,
  3 (administrator) `az`. `command_overrides` changes a command's letter, like ArcEmu's table of
  that name. `.account level NAME LETTERS` stores the level whose letters those are (or a number).
* **Selection:** a command acting on "the selected player" acts on you when nothing is selected
  (ArcEmu's `getSelectedChar`); several also act on a selected creature.
* **GM tag:** `.gm on` sets the `<GM>` flag and the GM chat tag. While the tag is on, players'
  whispers get ArcEmu's automatic reply unless `.gm allowwhispers NAME` lets them through.
  `.gm whisperblock` turns the tag on without the flag.
* **The rest of the GM system:** accounts with any permission log out at once, are not speed
  checked, may invite the other faction, and see the population on login; the `c` letter speaks
  every language and moderates every custom channel; the `u` letter receives `.gmannounce`.
  `gm_command_log` names the file ArcEmu's GM log goes to.

## Differences from ArcEmu

What CMaNGOS's schema or 1.12 decides differently, and ArcEmu bugs not copied:

* `.ban character` and `.unban character` ban and unban the character's **account**: CMaNGOS has no
  character bans. `ip_banned` holds addresses: a `/32` is dropped.
* `.recall` works on CMaNGOS's `game_tele` table (ArcEmu's `recall`).
* `.help` finds the commands you may use (ArcEmu's skips exactly those). `.recall portplayer`
  matches the location by its own letters (ArcEmu compares the whole command line).
  `.kick byplayer` no longer adds "There is no body online" after disconnecting someone.
  `.cheat explore` tells the player, not the GM, the second message. A bare `.server shutdown`
  waits the 5 seconds its help promises (ArcEmu's stops at once).
* `.server info` names this server, not ArcEmu. Item links use 1.12's link format.
* `.character additem` gives the whole count, in as many stacks as it takes.
* `.npc spawn` and `.gobject spawn` write CMaNGOS's `creature` and `gameobject` rows (a respawn time of
  120 seconds for creatures, the table's default); in a cluster only the GM's node knows the new spawn
  until the others restart.
* `.gobject scale` is not saved: CMaNGOS's `gameobject` has no size. `.gobject move` and `.gobject rotate`
  rewrite the spawn's row and keep its guid (ArcEmu gave the object a new one).
* `.gobject info` shows the size as a number (ArcEmu printed a float with `%%u`).
* `.quest giver` and `.quest finisher` name a game object by its own template (ArcEmu looks its id up
  among the items); ArcEmu's quest tables are CMaNGOS's (`creature_questrelation` and the like).
  `.quest start` gives the quest's source item, as accepting it does (ArcEmu's `receive_items` do not
  exist in this schema).
* `.castspellne` shows the cast in 1.12's `SMSG_SPELL_START` and `SMSG_SPELL_GO` layout (ArcEmu's
  bytes are 2.4.3's). `.dispelall` spares passive auras (talents, racials), and reaches the players
  of the GM's node of a cluster only, as `.admin castall` does. `.kill` and `.killplr` kill a player the way death by a
  creature's hand does, without its durability loss.
* `.npc vendoradditem` writes an unlimited `npc_vendor` row: CMaNGOS sells an item in its own
  `BuyCount`, so the amount is checked but not kept, and 1.12 has no extended costs (any is
  "invalid"). In a cluster the other nodes see the new ware after a restart.
* In a cluster, `.instance info`, `.instance shutdown` and `.instance reset` of a copy another node
  hosts are answered by that node; `.character showinstances` marks such a copy with its node in
  place of its status, which only that node knows.
* `.quest addstart`, `addfinish`, `addboth` and their `del` forms write CMaNGOS's
  `creature_questrelation` and `creature_involvedrelation`; ArcEmu's also wrote the creature's
  entry into the game object tables, making an unrelated game object a quest giver: not copied.
* `.character resetspells` and `resetskills` reset to what a new character of the race and class
  gets from CMaNGOS's creation (`playercreateinfo_*`, with skill caps for the level); the player, not
  the GM, reads "... reset all your spells to starting values." (ArcEmu sent it to the GM).
* `.quest item` lists the items the quest asks for (its `ReqItemId` columns): CMaNGOS has no
  `gameobject_quest_item_binding`. `.quest list` on a player reads its quest log as the client has it
  (ArcEmu's reads the saved `questlog` rows).
* `.gmTicket`: the rows ArcEmu builds with `GM_TICKET_MY_MASTER_COMPATIBLE` (`get`, `getId`, `delId`) are left
  out, as ArcEmu leaves them out by default. The answers go to `gm_client_channel` as ArcEmu's do; the
  commands work whenever it is set (ArcEmu's also need the channel to exist on the server). A
  ticket's assigned GM and comment are kept in memory only (CMaNGOS's `gm_tickets` has no columns
  for them); a removed ticket is kept as `state` 1 until deleted permanently. The client's ticket
  packets and result codes are 1.12's.
* `.character forcerename` sets CMaNGOS's `at_login` rename flag (ArcEmu's `forced_rename_pending`); the
  old name is reserved until the server restarts (ArcEmu's `banned_names` row; CMaNGOS keeps
  `reserved_name` in the world database, which the server does not write).
* `.invisible`: in a cluster, players of other nodes still see an invisible game master (their replica
  of it carries no invisibility yet).
* Arguments are read strictly: a number written wrong ("12abc", "abc") or a missing argument shows
  the command's help, where ArcEmu's C parsing read "12abc" as 12 and "abc" as 0 and went on.

## Working (%d)

| Command | Letter | Help |
|---|---|---|
%s

## Not yet implemented (%d)

These answer "Not yet implemented.", as ArcEmu's `HandleNYICommand` does: what they work on is not
done yet (among them AI agents and waypoint editing, possession, arenas, GM invisibility, flying).

| Command | Letter | Help |
|---|---|---|
%s
""" % (len(rows_done), "\n".join(rows_done), len(rows_todo), "\n".join(rows_todo)))


if __name__ == "__main__":
    main()
